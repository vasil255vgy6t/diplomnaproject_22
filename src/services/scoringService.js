function evaluateResult(totalScore) {
  if (totalScore <= 10) {
    return {
      level: 'Низький рівень напруження',
      recommendation: 'Ваш психологічний стан стабільний. Продовжуйте підтримувати баланс навчання та відпочинку.'
    };
  }

  if (totalScore <= 20) {
    return {
      level: 'Помірний рівень стресу',
      recommendation: 'Рекомендується звернути увагу на режим сну, відпочинок та регулярну фізичну активність.'
    };
  }

  return {
    level: 'Високий рівень емоційного виснаження',
    recommendation: 'Рекомендується звернутися до психолога закладу освіти або спеціаліста з ментального здоров’я.'
  };
}

module.exports = { evaluateResult };
